#!/usr/bin/env bash
# verify-wp-env.sh — Check a generated internal-license mu-plugin on the wp-env development site.
#
# Usage:
#   verify-wp-env.sh --mu-plugin FILE --mock FILE [--repo DIR] [--url URL] [--mu-dir DIR]
#                    [--user admin] [--password password]
#
#   --mu-plugin  the file generate.py wrote (e.g. tools/mu-plugins/<slug>-internal-license.php)
#   --mock       the file generate.py --verify-mock wrote
#   --repo       plugin repository with .wp-env.json (default: the git top level of the current directory)
#   --url        development site (default: http://localhost:<port in .wp-env.json>)
#   --mu-dir     host path of the site's wp-content/mu-plugins (default: found from ~/.wp-env/*/docker-compose.yml)
#
# Copies the mock (as 0-wcam-verify-mock.php, so it loads first) and the mu-plugin into mu-plugins, logs in,
# and runs five scenarios against the mock store: S0 no mu-plugin, S1 activation succeeds, S2 the store
# says "already activated", S3 activation fails, S4 the constant is missing. Nothing goes to the real store.
# On exit (also on failure or Ctrl-C) it removes both files and the options and transients it touched,
# then compares the client's options with what they were before.
#
# Exit status: 0 all checks passed, 1 a check failed, 2 bad input or the site is not reachable.
set -uo pipefail

MU_PLUGIN="" MOCK="" REPO="" URL="" MU_DIR="" USER_NAME="admin" PASSWORD="password"
while [ $# -gt 0 ]; do
	case "$1" in
		--mu-plugin) MU_PLUGIN="$2"; shift 2 ;;
		--mock) MOCK="$2"; shift 2 ;;
		--repo) REPO="$2"; shift 2 ;;
		--url) URL="$2"; shift 2 ;;
		--mu-dir) MU_DIR="$2"; shift 2 ;;
		--user) USER_NAME="$2"; shift 2 ;;
		--password) PASSWORD="$2"; shift 2 ;;
		-h|--help) sed -n '2,21p' "$0"; exit 0 ;;
		*) echo "ERROR: unknown option $1" >&2; exit 2 ;;
	esac
done

die() { echo "ERROR: $*" >&2; exit 2; }
[ -f "$MU_PLUGIN" ] || die "--mu-plugin is not a file"
[ -f "$MOCK" ] || die "--mock is not a file"
grep -q "AW_WC_AM_Internal_License_" "$MU_PLUGIN" || die "--mu-plugin was not generated by this skill"
grep -q "wcam_mock_mode" "$MOCK" || die "--mock was not generated by generate.py --verify-mock"

REPO="${REPO:-$(git rev-parse --show-toplevel 2>/dev/null)}"
[ -n "$REPO" ] && [ -f "$REPO/.wp-env.json" ] || die "no .wp-env.json in --repo ${REPO:-(none)}"
REPO="$(cd "$REPO" && pwd)"

if [ -z "$URL" ]; then
	PORT="$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1])).get("port", 8888))' "$REPO/.wp-env.json")" || die "cannot read the port from .wp-env.json"
	URL="http://localhost:${PORT}"
fi
URL="${URL%/}"

if [ -z "$MU_DIR" ]; then
	MATCHES="$(grep -l -F "${REPO}:" "$HOME"/.wp-env/*/docker-compose.yml 2>/dev/null)"
	[ "$(printf '%s\n' "$MATCHES" | grep -c .)" -eq 1 ] || die "cannot tell which ~/.wp-env directory mounts $REPO; pass --mu-dir"
	MU_DIR="$(dirname "$MATCHES")/WordPress/wp-content/mu-plugins"
fi
[ -d "$MU_DIR" ] || die "--mu-dir $MU_DIR is not a directory"

# Settings from the generated file: the array passed to the constructor at the end of the file.
conf() { sed -n "/^( new AW_WC_AM_Internal_License_/,\$ s/^[[:space:]]*'$1'[[:space:]]*=> '\{0,1\}\([^']*\)'\{0,1\},\$/\1/p" "$MU_PLUGIN" | head -1; }
PLUGIN_FILE="$(conf plugin_file)"
PRODUCT_ID="$(conf product_id)"
CLIENT_HAS_ID="$(conf client_has_product_id)"
SETTINGS_PAGE="$(conf settings_page)"
[ -n "$PLUGIN_FILE" ] && [ -n "$PRODUCT_ID" ] && [ -n "$CLIENT_HAS_ID" ] || die "cannot read the settings block of $MU_PLUGIN"
normalize() { printf '%s' "$1" | tr 'A-Z' 'a-z' | sed 's/[ _&?-]/_/g'; }
if [ "$CLIENT_HAS_ID" = "true" ]; then DATA_KEY="wc_am_client_$(normalize "$PRODUCT_ID")"; else DATA_KEY="wc_am_client_$(normalize "$(dirname "$PLUGIN_FILE")")"; fi
SETTINGS_PAGE="${SETTINGS_PAGE:-${DATA_KEY}_dashboard}"
STATE="${DATA_KEY}_internal_license"

MU_COPY="$MU_DIR/$(basename "$MU_PLUGIN")"
MOCK_COPY="$MU_DIR/0-wcam-verify-mock.php"
for f in "$MU_COPY" "$MOCK_COPY"; do
	[ -e "$f" ] && die "$f already exists; remove it (or finish the earlier run) first"
done

W="$(mktemp -d)"
JAR="$W/cookies.txt"
PASS=0
FAIL=0

wpcli() { (cd "$REPO" && npx wp-env run cli wp "$@" 2>/dev/null); }
wpeval() { wpcli eval "$1"; }
client_options() {
	wpeval "global \$wpdb; foreach ( \$wpdb->get_results( \$wpdb->prepare( \"SELECT option_name, option_value FROM {\$wpdb->options} WHERE option_name LIKE %s ORDER BY option_name\", '${DATA_KEY}%' ) ) as \$r ) { echo \$r->option_name, '=', \$r->option_value, PHP_EOL; }"
}

cleanup() {
	rm -f "$MU_COPY" "$MOCK_COPY"
	wpeval "foreach ( array( 'wcam_mock_mode', 'wcam_mock_log', 'wcam_mock_activated', 'wcam_mock_no_key', '${STATE}' ) as \$o ) { delete_option( \$o ); } delete_transient( '${STATE}_retry' ); delete_site_transient( 'update_plugins' );" >/dev/null
	AFTER="$(client_options)"
	echo
	if [ "$AFTER" = "${BEFORE:-}" ]; then
		echo "cleanup: removed both files; the client's options are as before"
	else
		echo "cleanup: removed both files, but the client's options differ from before:"
		diff <(printf '%s\n' "${BEFORE:-}") <(printf '%s\n' "$AFTER") | sed 's/^/  /'
	fi
	rm -f "$JAR"
	if [ "$FAIL" -gt 0 ]; then
		echo "pages kept for a look: $W"
	else
		rm -f "$W"/*.html
		rmdir "$W" 2>/dev/null
	fi
}

ok()  { PASS=$((PASS + 1)); echo "  ok   - $1"; }
bad() { FAIL=$((FAIL + 1)); echo "  FAIL - $1"; }
# expect yes|no LABEL FILE REGEX [page|row|update-row]: whether the Python regexp matches the page, the
# plugin's row on the Plugins screen, or its update row. {PAGE} in REGEX stands for the settings page slug.
expect() {
	if python3 -I - "$3" "$4" "${5:-page}" "$PLUGIN_FILE" "$SETTINGS_PAGE" <<'PY'; then got=yes; else got=no; fi
import re
import sys

path, pattern, scope, plugin, page = sys.argv[1:6]
with open(path, encoding="utf-8", errors="replace") as fh:
    html = fh.read()
plugin = re.escape(plugin)
if scope == "row":
    match = re.search(r'<tr(?![^>]*plugin-update-tr)[^>]*data-plugin="%s"[^>]*>.*?</tr>' % plugin, html, re.S)
    html = match.group(0) if match else ""
elif scope == "update-row":
    match = re.search(r'<tr[^>]*plugin-update-tr[^>]*data-plugin="%s"[^>]*>.*?</tr>' % plugin, html, re.S)
    html = match.group(0) if match else ""
sys.exit(0 if re.search(pattern.replace("{PAGE}", re.escape(page)), html, re.S) else 1)
PY
	if [ "$got" = "$1" ]; then ok "$2"; else bad "$2 (expected $1, got $got)"; fi
}
count_requests() { # count_requests ACTION
	wpcli option get wcam_mock_log --format=json | python3 -I -c 'import json,sys; print(sum(1 for e in json.load(sys.stdin) if e.get("action") == sys.argv[1]))' "$1" 2>/dev/null || echo 0
}
reset() { # reset MODE [no-key]
	wpeval "update_option( 'wcam_mock_mode', '$1' ); foreach ( array( 'wcam_mock_log', 'wcam_mock_activated', 'wcam_mock_no_key', '${STATE}' ) as \$o ) { delete_option( \$o ); } delete_transient( '${STATE}_retry' ); delete_site_transient( 'update_plugins' );" >/dev/null
	[ "${2:-}" = "no-key" ] && wpcli option update wcam_mock_no_key 1 >/dev/null
	return 0
}
page() { curl -s -b "$JAR" -c "$JAR" "$URL/wp-admin/$1" -o "$W/$2.html"; echo "$W/$2.html"; }

# Markers that do not depend on the site language.
NOTICE='notice-error">\s*<p>[^<]*<strong>[^<]*</strong>[^<]*<a href="[^"]*page={PAGE}"'
MENU='href="[^"]*page={PAGE}"'
AUTO_UPDATES='column-auto-updates.>\s*(<span class="label">|<a [^>]*class="toggle-auto-update)'
UPDATE_LINK='class="update-link"'
LICENSED='Licensed with the internal key \(mu-plugin\)'
PENDING='Internal key \(mu-plugin\): not activated yet'
WARNING='internal license could not be activated'

curl -s -o /dev/null "$URL/wp-login.php" || die "$URL is not reachable; start wp-env first"
BEFORE="$(client_options)"
trap cleanup EXIT
trap 'exit 1' INT TERM

echo "verify $(basename "$MU_PLUGIN") on $URL"
echo "  plugin $PLUGIN_FILE, data key $DATA_KEY, settings page $SETTINGS_PAGE"

curl -s -c "$JAR" -b "$JAR" -o /dev/null "$URL/wp-login.php"
CODE="$(curl -s -c "$JAR" -b "$JAR" -o /dev/null -w '%{http_code}' --data-urlencode "log=$USER_NAME" --data-urlencode "pwd=$PASSWORD" --data-urlencode testcookie=1 "$URL/wp-login.php")"
[ "$CODE" = "302" ] || die "cannot log in as $USER_NAME (HTTP $CODE)"

cp "$MOCK" "$MOCK_COPY"

echo "S0 mock only, no key (the plugin's usual unlicensed state)"
reset success no-key
P="$(page plugins.php s0)"
expect yes "the client's inactive notice shows" "$P" "$NOTICE"
expect yes "the license settings page is in the menu" "$P" "$MENU"
expect no "the auto-updates column offers auto-updates" "$P" "$AUTO_UPDATES" row

cp "$MU_PLUGIN" "$MU_COPY"

echo "S1 activation succeeds"
reset success
P="$(page plugins.php s1)"
expect no "no inactive notice" "$P" "$NOTICE"
expect no "the license settings page is not in the menu" "$P" "$MENU"
expect yes "the auto-updates column offers auto-updates (the client forces them on, as for a licensed customer)" "$P" "$AUTO_UPDATES" row
expect yes "the row says it is licensed with the internal key" "$P" "$LICENSED" row
expect no "no activation warning" "$P" "$WARNING"
LOG="$(wpcli option get wcam_mock_log --format=json)"
if printf '%s' "$LOG" | python3 -I -c '
import json, sys
want_id = sys.argv[1]
acts = [e for e in json.load(sys.stdin) if e.get("action") == "activate"]
ok = len(acts) == 1 and acts[0]["key_in_body"] and not acts[0]["key_in_url"] and acts[0]["key_ok"] and acts[0]["redirection"] == 0 and str(acts[0]["product_id"]) == want_id
sys.exit(0 if ok else 1)' "$PRODUCT_ID"; then
	ok "one activation, key in the POST body only, no redirects, product ID $PRODUCT_ID"
else
	bad "one activation, key in the POST body only, no redirects, product ID $PRODUCT_ID"; printf '%s\n' "$LOG" | sed 's/^/         | /'
fi
LOCATION="$(curl -s -b "$JAR" -o /dev/null -w '%{http_code} %{redirect_url}' "$URL/wp-admin/options-general.php?page=$SETTINGS_PAGE")"
case "$LOCATION" in "302 "*"/wp-admin/plugins.php") ok "the settings page sends you to the Plugins screen" ;; *) bad "the settings page sends you to the Plugins screen (got $LOCATION)" ;; esac
RAW="$(client_options)"
if printf '%s' "$RAW" | grep -q "verify0123456789abcdef"; then bad "the key is not in the database"; else ok "the key is not in the database"; fi
wpcli option update wcam_mock_log '[]' --format=json >/dev/null
P="$(page plugins.php s1b)"
[ "$(count_requests activate)" = "0" ] && ok "the next admin load does not activate again" || bad "the next admin load does not activate again"
expect yes "the Plugins screen offers the update (version 9.9.9 from the mock)" "$P" "$UPDATE_LINK" update-row

echo "S2 the store says the instance is already activated"
reset already
P="$(page plugins.php s2)"
expect yes "the row says it is licensed with the internal key" "$P" "$LICENSED" row
expect no "no activation warning" "$P" "$WARNING"
[ "$(count_requests status)" -ge 1 ] && ok "a status request confirmed the activation" || bad "a status request confirmed the activation"

echo "S3 activation fails"
reset fail
P="$(page plugins.php s3)"
expect no "no inactive notice from the client" "$P" "$NOTICE"
expect yes "the activation warning shows on the Plugins screen" "$P" "$WARNING"
expect no "the warning carries no markup from the store" "$P" "<b>license key</b>|&lt;b&gt;license key"
expect yes "the row says it is not activated yet" "$P" "$PENDING" row
wpcli option update wcam_mock_log '[]' --format=json >/dev/null
P="$(page index.php s3b)"
expect no "the warning does not show on the Dashboard" "$P" "$WARNING"
[ "$(count_requests activate)" = "0" ] && ok "no retry within the hour" || bad "no retry within the hour"

echo "S4 the mu-plugin is in place but the constant is missing"
reset success no-key
P="$(page plugins.php s4)"
expect yes "the client's inactive notice shows again" "$P" "$NOTICE"
expect yes "the license settings page is back in the menu" "$P" "$MENU"
expect no "the row has no internal-key note" "$P" "[Ii]nternal key \\(mu-plugin\\)" row
[ "$(count_requests activate)" = "0" ] && ok "nothing is activated" || bad "nothing is activated"

echo
echo "passed: $PASS, failed: $FAIL"
[ "$FAIL" -eq 0 ]
